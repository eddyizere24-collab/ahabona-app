  employment_type TEXT NOT NULL CHECK (employment_type IN ('full_time','part_time','contract','temporary','casual','internship','volunteer')),
  work_arrangement TEXT NOT NULL DEFAULT 'on_site' CHECK (work_arrangement IN ('on_site','hybrid','remote')),
  province TEXT,
  district TEXT,
  location_text TEXT,
  vacancies INTEGER NOT NULL DEFAULT 1 CHECK (vacancies BETWEEN 1 AND 10000),
  salary_min NUMERIC(14,2),
  salary_max NUMERIC(14,2),
  salary_currency CHAR(3) NOT NULL DEFAULT 'RWF',
  salary_period TEXT CHECK (salary_period IS NULL OR salary_period IN ('hourly','daily','weekly','monthly','yearly','one_off')),
  salary_visible BOOLEAN NOT NULL DEFAULT true,
  experience_min_years NUMERIC(4,1) CHECK (experience_min_years IS NULL OR experience_min_years BETWEEN 0 AND 80),
  education_level TEXT,
  requirements JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(requirements) = 'array'),
  responsibilities JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(responsibilities) = 'array'),
  application_method TEXT NOT NULL DEFAULT 'in_platform' CHECK (application_method IN ('in_platform','employer_contact','external_url')),
  application_instructions TEXT,
  external_application_url TEXT,
  application_email TEXT,
  deadline_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','pending_review','approved','rejected','closed','expired','archived')),
  moderation_note TEXT,
  reviewed_by_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(employer_user_id, organization_id) = 1),
  CHECK (salary_min IS NULL OR salary_min >= 0),
  CHECK (salary_max IS NULL OR salary_max >= 0),
  CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min),
  CHECK ((application_method <> 'external_url') OR external_application_url IS NOT NULL),
  CHECK ((work_arrangement = 'remote') OR (district IS NOT NULL OR location_text IS NOT NULL))
);

